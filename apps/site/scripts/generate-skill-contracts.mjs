import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const siteRoot = resolve(import.meta.dirname, "..");
const repoRoot = resolve(siteRoot, "../..");
const files = {
  ethics: "skills/ETHICS.md",
  "relevance-coarse-filter": "skills/relevance-coarse-filter/SKILL.md",
  "angle-generator": "skills/angle-generator/SKILL.md",
};

const contracts = Object.fromEntries(
  Object.entries(files).map(([name, path]) => [
    name,
    readFileSync(join(repoRoot, path), "utf8"),
  ]),
);
const output = `// Generated by scripts/generate-skill-contracts.mjs. Do not edit.
export const skillContracts = ${JSON.stringify(contracts, null, 2)} as const;
`;

writeFileSync(join(siteRoot, "lib/generated-skill-contracts.ts"), output);
console.log("Bundled canonical Newsjack skill contracts.");
